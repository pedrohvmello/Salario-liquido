import {describe,expect,it} from 'vitest'
import {readFileSync,statSync} from 'node:fs'
describe('Payrep public Pep presentation',()=>{
 const home=readFileSync('public/home.html','utf8')
 const styles=readFileSync('public/public-pages.css','utf8')
 it('publishes video on Home with controls, poster and native responsive layout',()=>{
  expect(home).toContain('id="home-pep-title"')
  expect(home).toContain('src="/media/pep-apresentacao.mp4"')
  expect(home).toContain('poster="/media/pep-apresentacao-poster.webp"')
  expect(home).toContain('controls playsinline preload="metadata"')
  expect(styles).toContain('.home-pep-feature')
  expect(styles).toContain('aspect-ratio:16/9')
 })
 it('uses a real optimized MP4 and poster rather than an external expiring URL',()=>{
  const media=statSync('public/media/pep-apresentacao.mp4')
  expect(media.size).toBeGreaterThan(20000)
  expect(media.size).toBeLessThan(1500000)
  expect(statSync('public/media/pep-apresentacao-poster.webp').size).toBeGreaterThan(1000)
 })
 it('autoplays the marketing video without transport controls and offers sound only',()=>{
  const paywall=readFileSync('src/components/PersonalPepPage.tsx','utf8')
  expect(paywall).toContain('autoPlay loop muted playsInline preload="auto"')
  expect(paywall).not.toContain('controls playsInline')
  expect(paywall).toContain('Ativar áudio da apresentação')
  expect(paywall).toContain('<PepBannerAnimation/>')
 })
 it('ships the chroma-keyed Pep as a local VP9 WebM asset with alpha metadata',()=>{
  const media=readFileSync('public/media/pep-banner-transparente.webm')
  const component=readFileSync('src/components/PepBannerAnimation.tsx','utf8')
  const styles=readFileSync('src/styles.css','utf8')
  expect(media.length).toBeGreaterThan(100_000)
  expect(media.length).toBeLessThan(1_500_000)
  expect(media.subarray(0,4).toString('hex')).toBe('1a45dfa3')
  expect(media.includes(Buffer.from('53c08101','hex'))).toBe(true)
  expect(component).toContain('src="/media/pep-banner-transparente.webm"')
  expect(component).toContain('autoPlay loop muted playsInline')
  expect(component).toContain('onError={()=>{setFailed(true);setPlaying(false)}}')
  expect(component).toContain("prefers-reduced-motion: reduce")
  expect(styles).toContain('.pep-banner-animation-video.is-playing')
 })
})
